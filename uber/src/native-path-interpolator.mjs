export function nativePathAt(value, curve = 'route') {
  const points = tables[curve];
  if (!points || !Number.isFinite(value))
    throw new Error('Invalid framework curve or fraction');
  const f = Math.fround,
    t = f(value);
  if (t <= 0) return 0;
  if (t >= 1) return 1;
  let start = 0,
    end = points.length - 1;
  while (end - start > 1) {
    const mid = (start + end) >> 1;
    if (t < points[mid][0]) end = mid;
    else start = mid;
  }
  const range = f(points[end][0] - points[start][0]);
  if (range === 0) return points[start][1];
  const fraction = f(f(t - points[start][0]) / range);
  return f(
    points[start][1] + f(fraction * f(points[end][1] - points[start][1])),
  );
}
