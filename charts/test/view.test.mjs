import test from 'node:test';
import assert from 'node:assert/strict';
import {initialView,changeView,calculateStudy} from '../src/view-model.mjs';
import {startViewServer} from '../src/view-server.mjs';
const config=()=>initialView({symbols:['X:A','X:B']});
test('view edits validate references, dates and scales before changing state',()=>{
 const c=config();
 assert.equal(c.normalization,'percent');
 assert.throws(()=>changeView(c,{scale:'log'}));
 assert.throws(()=>changeView(c,{drawings:[{id:'d',series:'missing',kind:'horizontal',start:{time:1,value:2}}]}));
 assert.throws(()=>changeView(c,{studies:[{id:'s',symbol:'X:C',kind:'SMA',length:20}]}));
 assert.throws(()=>changeView(c,{unknown:'option'}));
 const next=changeView(c,{from:'2026-10-01T00:00:00Z',to:'2026-10-31T00:00:00Z'});
 assert.equal(next.period,undefined);assert.equal(c.period,'year_to_date');
 const recolored=changeView(c,{series:[{id:'s1',color:'#ffffff'},{id:'s2'}]});
 assert.equal(recolored.series[0].symbol,'X:A');assert.equal(recolored.series[0].color,'#ffffff');
 assert.equal(recolored.series[1].color,c.series[1].color);
 const studied=changeView(c,{studies:[{kind:'RSI',length:14}]});
 assert.equal(studied.studies[0].symbol,'X:A');assert.ok(studied.studies[0].id);
 const single=changeView(studied,{chartType:'candlestick',removeSeries:['s2'],normalization:'price',scale:'log'});
 assert.equal(single.series.length,1);assert.equal(single.series[0].kind,'candlestick');
 const october=changeView(c,{timeframe:'1h',from:'2026-10-01T00:00:00Z',to:'2026-10-31T23:59:59Z',count:720});
 assert.equal(october.count,745);
 assert.throws(()=>changeView(c,{timeframe:'1h',from:'2025-01-01T00:00:00Z',to:'2026-01-01T00:00:00Z'}),/5000 bars/);
});
test('local study seed and warmup semantics are explicit',()=>{
 const rows=[1,2,3,4,5].map((close,time)=>({time,close}));
 assert.deepEqual(calculateStudy(rows,'SMA',3).map(r=>r.value),[2,3,4]);
 assert.deepEqual(calculateStudy(rows,'EMA',3).map(r=>r.value),[2,3,4]);
 assert.deepEqual(calculateStudy(rows,'RSI',3).map(r=>r.value),[100,100]);
 assert.deepEqual(calculateStudy(rows.map(r=>({...r,close:1})),'RSI',3).map(r=>r.value),[50,50]);
});
test('viewer protects data, rejects stale edits and preserves state on errors',async t=>{
 let calls=0;
 const service={execute:async()=>{calls++;return{data:[{time:1767225600,open:100,high:110,low:90,close:100},{time:1767312000,open:100,high:120,low:99,close:110}],instrument:{unit:'USD'},coverage:{returnedBars:2},warnings:[]};}};
 const live=await startViewServer({config:config(),key:'test-viewer-key',expiresAt:Date.now()+60000,service});
 t.after(()=>{live.server.closeAllConnections();live.server.close();});
 const base=`http://127.0.0.1:${live.port}`,headers={Authorization:'Bearer test-viewer-key','Content-Type':'application/json'};
 assert.equal((await fetch(base+'/api/view')).status,401);
 assert.equal((await fetch(base+'/charts.mjs')).status,200);
 assert.equal(calls,2);
 assert.deepEqual(await (await fetch(base+'/api/view?revision=1',{headers})).json(),{unchanged:true,revision:1});
 let r=await fetch(base+'/api/edit',{method:'POST',headers,body:JSON.stringify({revision:1,changes:{title:'Changed'}})});
 assert.equal(r.status,200);assert.equal((await r.json()).revision,2);assert.equal(calls,2);
 r=await fetch(base+'/api/edit',{method:'POST',headers,body:JSON.stringify({revision:1,changes:{title:'Stale'}})});
 assert.equal(r.status,409);
 r=await fetch(base+'/api/edit',{method:'POST',headers,body:JSON.stringify({revision:2,changes:{scale:'log'}})});
 assert.equal(r.status,400);assert.equal(live.state().config.title,'Changed');assert.equal(live.state().revision,2);
});
test('batched snapshot and stock screen use verified provider fields once per operation',async()=>{
 const {createCharts}=await import('../src/service.mjs');let captured;
 const app=createCharts({store:{load:async()=>null},sdk:{getScreener:async q=>{captured=q;return{rows:[{symbol:'X:A',values:{RSI:42,'RSI|60':55}}],totalCount:20};}}});
 const r=await app.execute('snapshot',{symbols:['X:A'],metrics:['RSI','MACD','EMA200'],timeframes:['D','1h']});
 assert.ok(captured.columns.includes('MACD.signal|60'));assert.equal(r.data[0].timeframes[0].values.RSI,42);
 assert.equal(r.data[0].timeframes[1].values.EMA200,null);
 const screen=await app.execute('screen',{'min-market-cap':1e10,'min-average-volume':1e6,'rsi-min':30,'rsi-max':45,limit:5});
 assert.ok(captured.filter.some(f=>f.left==='market_cap_basic'));
 assert.equal(screen.nextRequest.arguments.offset,1);assert.equal(screen.nextRequest.arguments['rsi-min'],30);
});
